-- Migration 001: Initial Schema for QualityApp PostgreSQL database
-- Normalized schema based on QualityApp mobile application models

-- 1. Employees Table
CREATE TABLE IF NOT EXISTS employees (
  id SERIAL PRIMARY KEY,
  employee_id VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'designer', 'qc')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0
);

-- 2. Drawings Table
CREATE TABLE IF NOT EXISTS drawings (
  id SERIAL PRIMARY KEY,
  drawing_no VARCHAR(100) NOT NULL UNIQUE,
  part_name VARCHAR(200) NOT NULL,
  customer VARCHAR(150) NOT NULL DEFAULT '',
  revision VARCHAR(50) NOT NULL DEFAULT 'A',
  material VARCHAR(150) NOT NULL DEFAULT '',
  unit VARCHAR(20) NOT NULL DEFAULT 'mm',
  notes TEXT NOT NULL DEFAULT '',
  invoice_no VARCHAR(100) NOT NULL DEFAULT '',
  invoice_date VARCHAR(50) NOT NULL DEFAULT '',
  drawing_rev_date VARCHAR(50) NOT NULL DEFAULT '',
  po_no VARCHAR(100) NOT NULL DEFAULT '',
  qty VARCHAR(50) NOT NULL DEFAULT '',
  treatment VARCHAR(150) NOT NULL DEFAULT '',
  hardness VARCHAR(100) NOT NULL DEFAULT '',
  image_uri TEXT,
  created_by INTEGER NOT NULL REFERENCES employees(id) ON UPDATE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0
);

-- 3. Dimensions Table
CREATE TABLE IF NOT EXISTS dimensions (
  id SERIAL PRIMARY KEY,
  drawing_id INTEGER NOT NULL REFERENCES drawings(id) ON DELETE CASCADE ON UPDATE CASCADE,
  dim_no INTEGER NOT NULL,
  description VARCHAR(255) NOT NULL DEFAULT '',
  nominal NUMERIC(12, 4) NOT NULL,
  nominal_text VARCHAR(100) NOT NULL DEFAULT '',
  tol_upper NUMERIC(12, 4) NOT NULL DEFAULT 0,
  tol_lower NUMERIC(12, 4) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_drawing_dim UNIQUE (drawing_id, dim_no)
);

-- 4. Checks Table (Inspection headers)
CREATE TABLE IF NOT EXISTS checks (
  id SERIAL PRIMARY KEY,
  client_id VARCHAR(100) UNIQUE,
  drawing_id INTEGER NOT NULL REFERENCES drawings(id) ON UPDATE CASCADE,
  checked_by INTEGER NOT NULL REFERENCES employees(id) ON UPDATE CASCADE,
  checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  result VARCHAR(10) NOT NULL CHECK (result IN ('PASS', 'FAIL')),
  instrument VARCHAR(150) NOT NULL DEFAULT '',
  inspector_notes TEXT NOT NULL DEFAULT '',
  inspector_name VARCHAR(100) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0
);

-- 5. Measurements Table (Sample readings per checked dimension)
CREATE TABLE IF NOT EXISTS measurements (
  id SERIAL PRIMARY KEY,
  check_id INTEGER NOT NULL REFERENCES checks(id) ON DELETE CASCADE ON UPDATE CASCADE,
  dimension_id INTEGER NOT NULL REFERENCES dimensions(id) ON UPDATE CASCADE,
  sample1 NUMERIC(12, 4),
  sample2 NUMERIC(12, 4),
  sample3 NUMERIC(12, 4),
  sample4 NUMERIC(12, 4),
  sample5 NUMERIC(12, 4),
  sample6 NUMERIC(12, 4),
  sample7 NUMERIC(12, 4),
  sample8 NUMERIC(12, 4),
  sample9 NUMERIC(12, 4),
  sample10 NUMERIC(12, 4),
  remarks TEXT NOT NULL DEFAULT '',
  pass SMALLINT NOT NULL CHECK (pass IN (0, 1)),
  instrument VARCHAR(150) NOT NULL DEFAULT '',
  sample_status TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Dispatches Table
CREATE TABLE IF NOT EXISTS dispatches (
  id SERIAL PRIMARY KEY,
  dispatch_no VARCHAR(100) NOT NULL UNIQUE,
  drawing_id INTEGER NOT NULL REFERENCES drawings(id) ON UPDATE CASCADE,
  drawing_no VARCHAR(100) NOT NULL DEFAULT '',
  part_name VARCHAR(200) NOT NULL DEFAULT '',
  po_no VARCHAR(100) NOT NULL DEFAULT '',
  invoice_no VARCHAR(100) NOT NULL DEFAULT '',
  qty VARCHAR(50) NOT NULL DEFAULT '',
  dispatched_by INTEGER NOT NULL REFERENCES employees(id) ON UPDATE CASCADE,
  dispatched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0
);

-- 7. Instruments Table
CREATE TABLE IF NOT EXISTS instruments (
  id SERIAL PRIMARY KEY,
  name VARCHAR(150) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted SMALLINT NOT NULL DEFAULT 0
);

-- 8. Sessions Table (Auth bearer tokens)
CREATE TABLE IF NOT EXISTS sessions (
  token VARCHAR(128) PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE ON UPDATE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
